export function getStoryRouteConfig(route) {
  return storyRouteConfigs[route] ?? null;
}

export function getNextStoryStageConfig(route, progress = 0) {
  const config = getStoryRouteConfig(route);
  if (!config) return null;
  return config.stageMissions.find((mission) => mission.stage === progress + 1) ?? null;
}
