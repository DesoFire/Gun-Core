export function getTrainingSkill(skillId) {
  return Object.values(trainingPools)
    .flatMap((pool) => pool.skills.map((skill) => ({ ...skill, poolId: Object.keys(trainingPools).find((id) => trainingPools[id] === pool), poolName: pool.name })))
    .find((skill) => skill.id === skillId);
}

export function getAllTrainingSkills() {
  return Object.entries(trainingPools).flatMap(([poolId, pool]) =>
    pool.skills.map((skill) => ({ ...skill, poolId, poolName: pool.name }))
  );
}
